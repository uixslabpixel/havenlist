// Bakes nearby places (restaurants, hospitals, supermarkets, transit) for every
// listing into assets/poi-data.js, using the free OpenStreetMap Overpass API.
// Run once with internet access:   node scripts/build-poi.mjs
// Needs Node 18+. Re-run whenever listing coordinates change.
import { readFileSync, writeFileSync } from "node:fs";
import vm from "node:vm";

const win = {};
vm.runInNewContext(readFileSync(new URL("../assets/geo.js", import.meta.url), "utf8"), { window: win, console });
const { COORDS, query, parse } = win.HLGeo;

const ENDPOINTS = [
  "https://overpass-api.de/api/interpreter",
  "https://overpass.kumi.systems/api/interpreter",
  "https://maps.mail.ru/osm/tools/overpass/api/interpreter"
];
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function fetchPlaces(center) {
  for (const url of ENDPOINTS) {
    try {
      const res = await fetch(url, {
        method: "POST",
        headers: { "Content-Type": "application/x-www-form-urlencoded", "User-Agent": "havenlist-build/1.0" },
        body: "data=" + encodeURIComponent(query(center))
      });
      if (res.ok) return parse(await res.json(), center);
      console.warn(url, res.status);
    } catch (e) { console.warn(url, e.message); }
  }
  return null;
}

const out = {};
for (const [id, center] of Object.entries(COORDS)) {
  const list = await fetchPlaces(center);
  if (list) { out[id] = list; console.log("ok  ", id, list.length, "places"); }
  else console.log("skip", id, "(the page will fetch live instead)");
  await sleep(1500); // be polite to the free servers
}
writeFileSync(
  new URL("../assets/poi-data.js", import.meta.url),
  "/* Generated by scripts/build-poi.mjs — do not edit by hand. */\nwindow.HL_POI = " + JSON.stringify(out) + ";\n"
);
console.log("Wrote assets/poi-data.js");
